static void mode_button_event(lv_event_t *event)
{
    if (lv_event_get_code(event) != LV_EVENT_CLICKED) return;
    const app_mode_t mode = (app_mode_t)(intptr_t)lv_event_get_user_data(event);
    esp_err_t err = mode_router_switch_to(mode);
    if (err != ESP_OK) ESP_LOGW(TAG, "Mode change failed: %s", esp_err_to_name(err));
}

static void main_button_event(lv_event_t *event)
{
    const lv_event_code_t code = lv_event_get_code(event);
    esp_err_t err = ESP_OK;
    if (s_requested_mode == APP_MODE_PUSH_TO_TALK) {
        if (code == LV_EVENT_PRESSED) {
            s_touch_down = true;                     /* immediate visual feedback */
            err = push_to_talk_on_pressed();
            s_listening = (err == ESP_OK);
            s_ptt_failed = (err != ESP_OK);
            ESP_LOGI(TAG, "PTT touch down -> %s", esp_err_to_name(err));
        } else if (code == LV_EVENT_RELEASED || code == LV_EVENT_PRESS_LOST) {
            if (s_touch_down) {
                err = push_to_talk_on_released();
                ESP_LOGI(TAG, "PTT touch up -> %s", esp_err_to_name(err));
            }
            s_touch_down = false;
            s_listening = false;
        }
    } else if (s_requested_mode == APP_MODE_MEDIA_REMOTE && code == LV_EVENT_CLICKED) {
        err = media_remote_send(MEDIA_COMMAND_PLAY_PAUSE);
    } else if (s_requested_mode == APP_MODE_HOME && code == LV_EVENT_CLICKED) {
        err = mode_router_switch_to(APP_MODE_MEDIA_REMOTE);
    } else if (s_requested_mode == APP_MODE_BADGE_TOOLS && code == LV_EVENT_CLICKED) {
        badge_tools_primary((uint64_t)esp_timer_get_time());
    }
    if (err != ESP_OK && err != ESP_ERR_INVALID_STATE && err != ESP_ERR_NOT_SUPPORTED) {
        ESP_LOGW(TAG, "Control unavailable: %s", esp_err_to_name(err));
    }
}

static void media_control_event(lv_event_t *event)
{
    if (lv_event_get_code(event) != LV_EVENT_CLICKED) return;
    const media_command_t command = (media_command_t)(intptr_t)lv_event_get_user_data(event);
    if (s_requested_mode == APP_MODE_BADGE_TOOLS) {
        if (command == MEDIA_COMMAND_PREVIOUS) badge_tools_reset((uint64_t)esp_timer_get_time());
        else if (command == MEDIA_COMMAND_NEXT) badge_tools_next_page();
        return;
    }
    esp_err_t err = media_remote_send(command);
    ESP_LOGI(TAG, "Media command %d -> %s", (int)command, esp_err_to_name(err));
}

/* Logs every touch-down point so a misaligned or dead touch panel is obvious in the serial log. */
static void touch_log_event(lv_event_t *event)
{
    lv_indev_t *indev = lv_event_get_indev(event);
    if (indev == NULL) indev = (lv_indev_t *)lv_event_get_target(event);
    lv_point_t p = { 0 };
    if (indev != NULL) lv_indev_get_point(indev, &p);
    ESP_LOGI(TAG, "touch at (%d, %d)", (int)p.x, (int)p.y);
}

/* --------------------------------------------------------------- refresh */

static void badge_tap_event(lv_event_t *event)
{
    if (lv_event_get_code(event) == LV_EVENT_CLICKED) {
        s_badge_info_on = !s_badge_info_on;
        s_badge_sig = UINT32_MAX;
    }
}

/* Returns true when the badge layer owns the screen. */
static bool refresh_badge(void)
{
    const bool on = (s_requested_mode == APP_MODE_BADGE) && !s_powering_off;
    set_hidden(s_badge, !on);
    if (!on) { s_badge_sig = UINT32_MAX; return false; }
    const badge_state_t st = badge_state();
    const int pct = (st == BADGE_STATE_RECEIVING) ? badge_progress() : 0;
    const bool show = s_badge_info_on || st != BADGE_STATE_PLAYING;
    const uint32_t sig = ((uint32_t)st << 16) | ((uint32_t)pct << 1) | (uint32_t)show;
    if (sig == s_badge_sig) return true;
    s_badge_sig = sig;
    if (st == BADGE_STATE_NO_VIDEO) lv_image_set_src(s_badge_img, NULL);
    set_hidden(s_badge_img, st != BADGE_STATE_PLAYING);
    set_hidden(s_badge_info, !show);
    static char text[160];
    switch (st) {
    case BADGE_STATE_RECEIVING:
        snprintf(text, sizeof text, "正在接收视频\n%d%%", pct);
        break;
    case BADGE_STATE_ERROR:
        snprintf(text, sizeof text, "吧唧启动失败\n请看串口日志");
        break;
    default:
        snprintf(text, sizeof text, "%s手机连 WiFi\n" BADGE_WIFI_SSID "\n密码 " BADGE_WIFI_PASS "\n浏览器打开\n" BADGE_URL,
                 st == BADGE_STATE_NO_VIDEO ? "还没有视频\n" : "");
        break;
    }
    set_label(s_badge_info, text);
    return true;
}

static void refresh_ui(lv_timer_t *timer)
{
    (void)timer;
    if (refresh_badge()) return;
    if (s_powering_off) {
        set_label(s_title, "正在关机");
        set_label(s_subtitle, "");
        set_label_font(s_center_label, UI_FONT);
        set_label(s_center_label, "再见");
        set_label(s_state, "按下键开机");
        set_label(s_note, "");
        set_hidden(s_mic, true);
        set_hidden(s_center_label, false);
        set_hidden(s_media_controls, true);
        set_hidden(s_prev_button, true);
        set_hidden(s_next_button, true);
        set_hidden(s_mode_controls, true);
        set_deco(false, false);
        s_ui_signature = UINT64_MAX;
        return;
    }

    const app_mode_t mode = s_requested_mode;
    const bool connected = ble_hid_is_connected();
    const ble_hid_state_t ble_state = ble_hid_state();
    const bool listening = s_listening;
    const bool touch_down = s_touch_down;
    const bool failed = s_ptt_failed;
    const bool ptt_ok = ble_hid_ptt_key_configured();
    badge_tools_snapshot_t tools = {0};
    if (mode == APP_MODE_BADGE_TOOLS) badge_tools_snapshot((uint64_t)esp_timer_get_time(), &tools);
    const uint64_t signature = ((uint64_t)ble_state << 48) | ((uint64_t)mode << 40) |
                               ((uint64_t)connected << 39) | ((uint64_t)listening << 38) |
                               ((uint64_t)touch_down << 37) | ((uint64_t)failed << 36) |
                               ((uint64_t)ptt_ok << 35) | ((uint64_t)tools.page << 32) |
                               ((uint64_t)tools.running << 31) |
                               ((uint64_t)(tools.elapsed_ms / 1000u & 0xFFFFu) << 15) |
                               (uint64_t)(tools.bubbles_popped & 0x7FFFu);
    if (signature == s_ui_signature) return;   /* nothing changed: no redraw */
    s_ui_signature = signature;

    const char *link = connected ? "蓝牙已连接" :
                       ble_state == BLE_HID_STATE_ADVERTISING ? "可配对 · Omarchy Orb" :
                       ble_state == BLE_HID_STATE_FAILED ? "蓝牙启动失败" : "蓝牙未连接";
    const bool is_ptt = (mode == APP_MODE_PUSH_TO_TALK);
    const bool is_media = (mode == APP_MODE_MEDIA_REMOTE);
    const bool is_tools = (mode == APP_MODE_BADGE_TOOLS);
    const bool tools_stopwatch = tools.page == BADGE_TOOL_STOPWATCH;

    set_hidden(s_media_controls, !is_media);
    set_hidden(s_prev_button, !(is_media || is_tools));
    set_hidden(s_next_button, !(is_media || is_tools));
    set_hidden(s_mode_controls, mode != APP_MODE_HOME);
    if (is_tools) {
        lv_obj_t *left = lv_obj_get_child(s_prev_button, 0);
        lv_obj_t *right = lv_obj_get_child(s_next_button, 0);
        set_label_font(left, UI_FONT);
        set_label_font(right, UI_FONT);
        set_label(left, "复位");
        set_label(right, "换页");
    } else {
        lv_obj_t *left = lv_obj_get_child(s_prev_button, 0);
        lv_obj_t *right = lv_obj_get_child(s_next_button, 0);
        set_label_font(left, ICON_FONT);
        set_label_font(right, ICON_FONT);
        set_label(left, LV_SYMBOL_PREV);
        set_label(right, LV_SYMBOL_NEXT);
    }
    set_hidden(s_mic, !is_ptt);
    set_hidden(s_center_label, is_ptt);
    lv_obj_invalidate(s_mic);

    if (is_ptt) {
        const bool lit = touch_down && listening;
        set_deco(true, lit);
        set_label(s_title, "按住说话");
        set_label(s_subtitle, link);
        set_bg_color(s_center_button, lit ? COLOR_AMBER : (touch_down ? COLOR_PRESSED : 0x211713));
        set_border_color(s_center_button, lit ? COLOR_AMBER_HI : 0xA64E35);
        if (lit) {
            set_label(s_state, "● 聆听中");
            set_label(s_note, "松开结束");
        } else if (touch_down || failed) {
            set_label(s_state, !connected ? "未发送：蓝牙未连接" :
                               !ptt_ok ? "未发送：键位未配置" : "未发送");
            set_label(s_note, connected ? "" : "请先在电脑上配对");
        } else {
            set_label(s_state, "按住中间按钮或上键");
            set_label(s_note, "");
        }
    } else if (is_media) {
        set_deco(false, false);
        set_bg_color(s_center_button, COLOR_BUTTON);
        set_border_color(s_center_button, 0x8B4A35);
        set_label(s_title, "媒体遥控");
        set_label(s_subtitle, link);
        set_label_font(s_center_label, ICON_FONT);
        set_label(s_center_label, LV_SYMBOL_PLAY "  " LV_SYMBOL_PAUSE);
        set_label(s_state, connected ? "" : "请先在电脑上配对");
        set_label(s_note, "");
    } else if (is_tools) {
        set_deco(false, false);
        set_bg_color(s_center_button, COLOR_BUTTON);
        set_border_color(s_center_button, COLOR_AMBER);
        set_label(s_title, tools_stopwatch ? "随身秒表" : "泡泡纸");
        set_label(s_subtitle, tools_stopwatch ? "The Badge · 轻量工具" : "The Badge · 轻松一下");
        set_label_font(s_center_label, UI_FONT);
        if (tools_stopwatch) {
            static char clock_text[24];
            const uint64_t seconds = tools.elapsed_ms / 1000u;
            snprintf(clock_text, sizeof clock_text, "%02llu:%02llu:%02llu",
                     (unsigned long long)(seconds / 3600u),
                     (unsigned long long)((seconds / 60u) % 60u),
                     (unsigned long long)(seconds % 60u));
            set_label(s_center_label, clock_text);
            set_label(s_state, tools.running ? "轻触暂停" : "轻触开始");
            set_label(s_note, "左侧复位 · 右侧换页");
        } else {
            static char bubble_text[32];
            snprintf(bubble_text, sizeof bubble_text, "泡泡纸\n%04u", tools.bubbles_popped);
            set_label(s_center_label, bubble_text);
            set_label(s_state, "轻触戳泡泡");
            set_label(s_note, "左侧清零 · 右侧换页");
        }
    } else if (mode == APP_MODE_STANDBY_PET) {
        set_deco(false, false);
        set_bg_color(s_center_button, COLOR_BUTTON);
        set_border_color(s_center_button, 0x8B4A35);
        set_label(s_title, "待机");
        set_label(s_subtitle, link);
        set_label_font(s_center_label, UI_FONT);
        set_label(s_center_label, "^_^");
        set_label(s_state, "按下键返回主菜单");
        set_label(s_note, "");
    } else {
        set_deco(false, false);
        set_bg_color(s_center_button, COLOR_BUTTON);
        set_border_color(s_center_button, 0x8B4A35);
        set_label(s_title, "圆屏遥控器");
        set_label(s_subtitle, link);
        set_label_font(s_center_label, UI_FONT);
        set_label(s_center_label, "媒体\n遥控");
        set_label(s_state, "");
        set_label(s_note, "");
    }
}

/* ------------------------------------------------------------------ init */

esp_err_t board_port_init(void)
{
    lv_display_t *display = bsp_display_start();
    ESP_RETURN_ON_FALSE(display != NULL, ESP_FAIL, TAG, "Waveshare BSP display/touch init failed");
    ESP_RETURN_ON_ERROR(bsp_display_lock(-1), TAG, "LVGL lock failed");

    lv_obj_t *screen = lv_screen_active();
    lv_obj_set_style_bg_color(screen, lv_color_hex(COLOR_BG), 0);
    lv_obj_set_style_bg_opa(screen, LV_OPA_COVER, 0);
    lv_obj_set_style_pad_all(screen, 0, 0);
    lv_obj_clear_flag(screen, LV_OBJ_FLAG_SCROLLABLE);

    s_deco = lv_obj_create(screen);
    lv_obj_remove_style_all(s_deco);
    lv_obj_set_size(s_deco, FACE_SIZE, FACE_SIZE);
    lv_obj_center(s_deco);
    lv_obj_clear_flag(s_deco, LV_OBJ_FLAG_CLICKABLE | LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_add_event_cb(s_deco, deco_draw_event, LV_EVENT_DRAW_MAIN, NULL);

    /* Layout (y): title 64, subtitle 98, button 133..333, state 344, controls 378..424. */
    s_title = make_label(screen, "圆屏遥控器", UI_FONT, COLOR_TEXT, 300);
    lv_obj_align(s_title, LV_ALIGN_TOP_MID, 0, 64);
    s_subtitle = make_label(screen, "蓝牙未连接", UI_FONT, COLOR_MUTED, 300);
    lv_obj_align(s_subtitle, LV_ALIGN_TOP_MID, 0, 98);

    s_center_button = lv_button_create(screen);
    lv_obj_remove_style_all(s_center_button);
    lv_obj_set_size(s_center_button, BTN_D, BTN_D);
    lv_obj_center(s_center_button);
    lv_obj_set_style_radius(s_center_button, LV_RADIUS_CIRCLE, 0);
    lv_obj_set_style_bg_opa(s_center_button, LV_OPA_COVER, 0);
    lv_obj_set_style_bg_color(s_center_button, lv_color_hex(COLOR_BUTTON), 0);
    lv_obj_set_style_border_width(s_center_button, 4, 0);
    lv_obj_set_style_border_color(s_center_button, lv_color_hex(0x8B4A35), 0);
    lv_obj_set_style_border_color(s_center_button, lv_color_hex(COLOR_AMBER), LV_STATE_PRESSED);
    lv_obj_clear_flag(s_center_button, LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_add_event_cb(s_center_button, main_button_event, LV_EVENT_ALL, NULL);

    s_center_label = make_label(s_center_button, "媒体\n遥控", UI_FONT, COLOR_TEXT, BTN_D - 40);
    lv_obj_set_height(s_center_label, LV_SIZE_CONTENT);
    lv_label_set_long_mode(s_center_label, LV_LABEL_LONG_MODE_WRAP);
    lv_obj_center(s_center_label);

    s_mic = lv_obj_create(s_center_button);
    lv_obj_remove_style_all(s_mic);
    lv_obj_set_size(s_mic, 100, 100);
    lv_obj_center(s_mic);
    lv_obj_clear_flag(s_mic, LV_OBJ_FLAG_CLICKABLE | LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_add_flag(s_mic, LV_OBJ_FLAG_EVENT_BUBBLE);
    lv_obj_add_event_cb(s_mic, mic_draw_event, LV_EVENT_DRAW_MAIN, NULL);
    lv_obj_add_flag(s_mic, LV_OBJ_FLAG_HIDDEN);

    s_state = make_label(screen, "", UI_FONT, COLOR_TEXT, 300);
    lv_obj_align(s_state, LV_ALIGN_TOP_MID, 0, 344);
    s_note = make_label(screen, "", UI_FONT, COLOR_MUTED, 260);
    lv_obj_align(s_note, LV_ALIGN_TOP_MID, 0, 378);

    /* Previous / next: round side buttons, as in the now-playing reference. */
    s_prev_button = make_button(screen, LV_SYMBOL_PREV, ICON_FONT, 64, 64, LV_RADIUS_CIRCLE);
    lv_obj_align(s_prev_button, LV_ALIGN_CENTER, -152, 0);
    lv_obj_add_event_cb(s_prev_button, media_control_event, LV_EVENT_CLICKED,
                        (void *)(intptr_t)MEDIA_COMMAND_PREVIOUS);
    s_next_button = make_button(screen, LV_SYMBOL_NEXT, ICON_FONT, 64, 64, LV_RADIUS_CIRCLE);
    lv_obj_align(s_next_button, LV_ALIGN_CENTER, 152, 0);
    lv_obj_add_event_cb(s_next_button, media_control_event, LV_EVENT_CLICKED,
                        (void *)(intptr_t)MEDIA_COMMAND_NEXT);

    s_media_controls = make_row(screen, 260, 46, 14);
    lv_obj_align(s_media_controls, LV_ALIGN_TOP_MID, 0, 376);
    static const struct { const char *icon; media_command_t command; } controls[] = {
        { LV_SYMBOL_VOLUME_MID, MEDIA_COMMAND_VOLUME_DOWN },
        { LV_SYMBOL_MUTE,       MEDIA_COMMAND_MUTE },
        { LV_SYMBOL_VOLUME_MAX, MEDIA_COMMAND_VOLUME_UP },
    };
    for (size_t i = 0; i < sizeof(controls) / sizeof(controls[0]); ++i) {
        lv_obj_t *button = make_button(s_media_controls, controls[i].icon, ICON_FONT, 72, 44, 22);
        lv_obj_add_event_cb(button, media_control_event, LV_EVENT_CLICKED,
                            (void *)(intptr_t)controls[i].command);
    }

    s_mode_controls = make_row(screen, 300, 48, 4);
    lv_obj_align(s_mode_controls, LV_ALIGN_TOP_MID, 0, 352);
    static const struct { const char *text; app_mode_t mode; } modes[] = {
        { "媒体", APP_MODE_MEDIA_REMOTE }, { "PTT", APP_MODE_PUSH_TO_TALK },
        { "待机", APP_MODE_STANDBY_PET }, { "吧唧", APP_MODE_BADGE },
        { "工具", APP_MODE_BADGE_TOOLS },
    };
    for (size_t i = 0; i < sizeof(modes) / sizeof(modes[0]); ++i) {
        lv_obj_t *button = make_button(s_mode_controls, modes[i].text, UI_FONT, 52, 46, 16);
        lv_obj_add_event_cb(button, mode_button_event, LV_EVENT_CLICKED,
                            (void *)(intptr_t)modes[i].mode);
    }

    /* Badge layer last so it sits on top of everything; tap toggles the upload info. */
    s_badge = lv_obj_create(screen);
    lv_obj_remove_style_all(s_badge);
    lv_obj_set_size(s_badge, FACE_SIZE, FACE_SIZE);
    lv_obj_center(s_badge);
    lv_obj_set_style_bg_color(s_badge, lv_color_hex(0x000000), 0);
    lv_obj_set_style_bg_opa(s_badge, LV_OPA_COVER, 0);
    lv_obj_clear_flag(s_badge, LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_add_flag(s_badge, LV_OBJ_FLAG_CLICKABLE);
    lv_obj_add_event_cb(s_badge, badge_tap_event, LV_EVENT_CLICKED, NULL);
    s_badge_img = lv_image_create(s_badge);
    lv_obj_center(s_badge_img);
    lv_obj_clear_flag(s_badge_img, LV_OBJ_FLAG_CLICKABLE);
    s_badge_info = make_label(s_badge, "", UI_FONT, COLOR_TEXT, 300);
    lv_obj_set_height(s_badge_info, LV_SIZE_CONTENT);
    lv_label_set_long_mode(s_badge_info, LV_LABEL_LONG_MODE_WRAP);
    lv_obj_set_style_text_align(s_badge_info, LV_TEXT_ALIGN_CENTER, 0);
    lv_obj_set_style_bg_color(s_badge_info, lv_color_hex(0x000000), 0);
    lv_obj_set_style_bg_opa(s_badge_info, LV_OPA_70, 0);
    lv_obj_set_style_pad_all(s_badge_info, 10, 0);
    lv_obj_set_style_radius(s_badge_info, 16, 0);
    lv_obj_center(s_badge_info);
    lv_obj_add_flag(s_badge, LV_OBJ_FLAG_HIDDEN);

    lv_indev_t *touch = bsp_display_get_input_dev();
    if (touch != NULL) lv_indev_add_event_cb(touch, touch_log_event, LV_EVENT_PRESSED, NULL);
    else ESP_LOGW(TAG, "No touch input device registered");

    lv_timer_create(refresh_ui, 60, NULL);
    refresh_ui(NULL);
    bsp_display_unlock();
    ESP_LOGI(TAG, "Waveshare BSP display + CST9217 touch initialized (466x466)");
    return ESP_OK;
}

/* ------------------------------------------------------------ public API */

void board_port_render_mode(app_mode_t mode)
{
    s_requested_mode = mode;
    s_listening = false;
    s_touch_down = false;
    s_ptt_failed = false;
}

void board_port_show_pet_expression(pet_expression_t expression)
{
    (void)expression;
}

/* Physical PWR key PTT: mirrors the touch hold so the screen gives feedback too. */
void board_port_set_listening(bool listening)
{
    s_listening = listening;
    s_touch_down = listening;
    s_ptt_failed = false;
}

void board_port_set_ptt_failed(bool failed)
{
    s_ptt_failed = failed;
    s_touch_down = failed;
    if (failed) s_listening = false;
}

void board_port_ui_lock(void)
{
    (void)bsp_display_lock(-1);
}

void board_port_ui_unlock(void)
{
    bsp_display_unlock();
}

void board_port_show_power_off(void)
{
    s_powering_off = true;
}

void board_port_badge_show_frame(const void *image_dsc)
{
    if (bsp_display_lock(-1) != ESP_OK) return;
    if (s_requested_mode == APP_MODE_BADGE && s_badge_img && !s_powering_off) {
        /* Player alternates two buffers, so the src pointer changes every frame. */
        lv_image_set_src(s_badge_img, image_dsc);
        set_hidden(s_badge_img, false);
        lv_obj_invalidate(s_badge_img);
        /* Render right here, in the player task (core 1), instead of leaving a full-screen
         * redraw to the LVGL task: back-to-back 466x466 redraws there starved IDLE0 and
         * froze the board (same failure as the earlier task_wdt hang). */
        lv_refr_now(NULL);
    }
    bsp_display_unlock();
}
