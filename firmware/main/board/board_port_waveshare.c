/*
 * Round 466x466 UI (Wabi style, see docs/hark/reference/target-*.webp).
 *
 * Performance rules learned on the device (task_wdt in lv_draw_sw_box_shadow):
 *  - no box shadows, no transformed (rotated) objects;
 *  - static decoration (dial ticks, PTT level bars, halo) is drawn by ONE object
 *    with plain lines/arcs;
 *  - refresh_ui only touches LVGL when the UI state actually changed.
 *
 * Text uses rsr_font_cjk_24 (subset of Noto Sans SC, generated by
 * tools/gen_font.sh from every string in this file). Icons use the built-in
 * Montserrat 24 symbol glyphs. If you add Chinese text, re-run the generator.
 */

static const char *TAG = "board_waveshare";
LV_FONT_DECLARE(rsr_font_cjk_24);
#define UI_FONT   (&rsr_font_cjk_24)
#define ICON_FONT (&lv_font_montserrat_24)

#define FACE_SIZE       466
#define FACE_CENTER     233
#define TICK_COUNT      60
#define TICK_RADIUS     198
#define BTN_D           200            /* centre button diameter */
#define BAR_COUNT       13             /* PTT level bars per side */

#define COLOR_BG        0x080909
#define COLOR_TICK      0x39302D
#define COLOR_TICK_MAJ  0x704532
#define COLOR_AMBER     0xF15B3D
#define COLOR_AMBER_HI  0xFF9B73
#define COLOR_TEXT      0xF2EEE9
#define COLOR_MUTED     0x928B85
#define COLOR_BUTTON    0x171310
#define COLOR_BTN_EDGE  0x45352E
#define COLOR_PRESSED   0x3A2018
#define COLOR_INK       0x1A0E0A

