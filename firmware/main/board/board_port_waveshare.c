/* ------------------------------------------------------------------ helpers */

static void set_label(lv_obj_t *label, const char *text)
{
    if (label == NULL || text == NULL) return;
    const char *current = lv_label_get_text(label);
    if (current != NULL && strcmp(current, text) == 0) return;
    lv_label_set_text(label, text);
}

static void set_label_font(lv_obj_t *label, const lv_font_t *font)
{
    if (lv_obj_get_style_text_font(label, LV_PART_MAIN) == font) return;
    lv_obj_set_style_text_font(label, font, 0);
}

static void set_bg_color(lv_obj_t *obj, uint32_t color)
{
    if (lv_color_to_u32(lv_obj_get_style_bg_color(obj, LV_PART_MAIN)) ==
        lv_color_to_u32(lv_color_hex(color))) return;
    lv_obj_set_style_bg_color(obj, lv_color_hex(color), 0);
}

static void set_border_color(lv_obj_t *obj, uint32_t color)
{
    if (lv_color_to_u32(lv_obj_get_style_border_color(obj, LV_PART_MAIN)) ==
        lv_color_to_u32(lv_color_hex(color))) return;
    lv_obj_set_style_border_color(obj, lv_color_hex(color), 0);
}

static void set_hidden(lv_obj_t *obj, bool hidden)
{
    if (obj == NULL) return;
    if (lv_obj_has_flag(obj, LV_OBJ_FLAG_HIDDEN) == hidden) return;
    if (hidden) lv_obj_add_flag(obj, LV_OBJ_FLAG_HIDDEN);
    else lv_obj_clear_flag(obj, LV_OBJ_FLAG_HIDDEN);
}

static void set_deco(bool ptt, bool lit)
{
    if (s_deco_ptt == ptt && s_deco_lit == lit) return;
    s_deco_ptt = ptt;
    s_deco_lit = lit;
    if (s_deco != NULL) lv_obj_invalidate(s_deco);
}

static lv_obj_t *make_label(lv_obj_t *parent, const char *text, const lv_font_t *font,
                            uint32_t color, int32_t width)
{
    lv_obj_t *label = lv_label_create(parent);
    lv_obj_set_style_text_font(label, font, 0);
    lv_obj_set_style_text_color(label, lv_color_hex(color), 0);
    lv_obj_set_style_text_align(label, LV_TEXT_ALIGN_CENTER, 0);
    if (width > 0) {
        lv_obj_set_width(label, width);
        lv_obj_set_height(label, 32);          /* one line; never wrap into neighbours */
    }
    lv_label_set_long_mode(label, LV_LABEL_LONG_MODE_CLIP);
    lv_label_set_text(label, text);
    return label;
}

static lv_obj_t *make_button(lv_obj_t *parent, const char *text, const lv_font_t *font,
                             int32_t width, int32_t height, int32_t radius)
{
    lv_obj_t *button = lv_button_create(parent);
    lv_obj_remove_style_all(button);
    lv_obj_set_size(button, width, height);
    lv_obj_set_style_radius(button, radius, 0);
    lv_obj_set_style_bg_opa(button, LV_OPA_COVER, 0);
    lv_obj_set_style_bg_color(button, lv_color_hex(COLOR_BUTTON), 0);
    lv_obj_set_style_bg_color(button, lv_color_hex(COLOR_PRESSED), LV_STATE_PRESSED);
    lv_obj_set_style_border_width(button, 2, 0);
    lv_obj_set_style_border_color(button, lv_color_hex(COLOR_BTN_EDGE), 0);
    lv_obj_set_style_border_color(button, lv_color_hex(COLOR_AMBER), LV_STATE_PRESSED);
    lv_obj_clear_flag(button, LV_OBJ_FLAG_SCROLLABLE);
    lv_obj_t *label = make_label(button, text, font, COLOR_TEXT, 0);
    lv_obj_center(label);
    return button;
}

static lv_obj_t *make_row(lv_obj_t *parent, int32_t width, int32_t height, int32_t gap)
{
    lv_obj_t *row = lv_obj_create(parent);
    lv_obj_remove_style_all(row);
    lv_obj_set_size(row, width, height);
    lv_obj_set_style_pad_column(row, gap, 0);
    lv_obj_set_flex_flow(row, LV_FLEX_FLOW_ROW);
    lv_obj_set_flex_align(row, LV_FLEX_ALIGN_CENTER, LV_FLEX_ALIGN_CENTER, LV_FLEX_ALIGN_CENTER);
    lv_obj_clear_flag(row, LV_OBJ_FLAG_SCROLLABLE | LV_OBJ_FLAG_CLICKABLE);
    return row;
}

/* ------------------------------------------------------------- custom draw */

static void draw_line(lv_layer_t *layer, float x1, float y1, float x2, float y2,
                      int32_t width, uint32_t color)
{
    lv_draw_line_dsc_t dsc;
    lv_draw_line_dsc_init(&dsc);
    dsc.color = lv_color_hex(color);
    dsc.width = width;
    dsc.round_start = 1;
    dsc.round_end = 1;
    dsc.p1.x = (lv_value_precise_t)lroundf(x1);
    dsc.p1.y = (lv_value_precise_t)lroundf(y1);
    dsc.p2.x = (lv_value_precise_t)lroundf(x2);
    dsc.p2.y = (lv_value_precise_t)lroundf(y2);
    lv_draw_line(layer, &dsc);
}

static void draw_arc(lv_layer_t *layer, int32_t cx, int32_t cy, int32_t radius, int32_t width,
                     int32_t start, int32_t end, uint32_t color)
{
    lv_draw_arc_dsc_t dsc;
    lv_draw_arc_dsc_init(&dsc);
    dsc.color = lv_color_hex(color);
    dsc.width = width;
    dsc.center.x = cx;
    dsc.center.y = cy;
    dsc.radius = radius;
    dsc.start_angle = start;
    dsc.end_angle = end;
    dsc.rounded = 1;
    lv_draw_arc(layer, &dsc);
}

static void deco_draw_event(lv_event_t *event)
{
    lv_layer_t *layer = lv_event_get_layer(event);
    lv_area_t a;
    lv_obj_get_coords(lv_event_get_target_obj(event), &a);
    const float cx = a.x1 + FACE_CENTER;
    const float cy = a.y1 + FACE_CENTER;

    /* Outer bezel rings. */
    draw_arc(layer, (int32_t)cx, (int32_t)cy, 219, 2, 0, 360, 0x272320);
    draw_arc(layer, (int32_t)cx, (int32_t)cy, 201, 1, 0, 360, 0x211C19);

    /* Dial ticks (every 6 degrees, major every 30). */
    for (int t = 0; t < TICK_COUNT; ++t) {
        const float ang = ((float)t * 6.0f - 90.0f) * 0.01745329252f;
        const bool major = (t % 5) == 0;
        const float len = major ? 14.0f : 7.0f;
        const float c = cosf(ang), s = sinf(ang);
        const float r1 = TICK_RADIUS - len / 2.0f, r2 = TICK_RADIUS + len / 2.0f;
        uint32_t color = major ? COLOR_TICK_MAJ : COLOR_TICK;
        if (s_deco_ptt && s_deco_lit && major) color = COLOR_AMBER;
        draw_line(layer, cx + c * r1, cy + s * r1, cx + c * r2, cy + s * r2, major ? 3 : 2, color);
    }

    if (!s_deco_ptt) return;

    /* PTT: halo ring around the button and two banks of level bars. */
    draw_arc(layer, (int32_t)cx, (int32_t)cy, BTN_D / 2 + 12, 6, 0, 360,
             s_deco_lit ? 0x7A2E1C : 0x24160F);
    static const uint8_t lengths[BAR_COUNT] = { 6, 10, 14, 10, 18, 12, 22, 12, 18, 10, 14, 10, 6 };
    for (int side = 0; side < 2; ++side) {
        for (int i = 0; i < BAR_COUNT; ++i) {
            float deg = -36.0f + (float)i * 6.0f;          /* right bank: -36..36 */
            if (side) deg = 180.0f - deg;                  /* left bank mirrored */
            const float ang = deg * 0.01745329252f;
            const float c = cosf(ang), s = sinf(ang);
            const float r1 = 150.0f, r2 = 150.0f + (float)lengths[i];
            draw_line(layer, cx + c * r1, cy + s * r1, cx + c * r2, cy + s * r2, 3,
                      s_deco_lit ? COLOR_AMBER : 0x3A2A24);
        }
    }
}

/* Microphone glyph, drawn so it needs no icon font. */
static void mic_draw_event(lv_event_t *event)
{
    lv_layer_t *layer = lv_event_get_layer(event);
    lv_area_t a;
    lv_obj_get_coords(lv_event_get_target_obj(event), &a);
    const int32_t cx = (a.x1 + a.x2) / 2;
    const int32_t cy = (a.y1 + a.y2) / 2;
    const bool lit = s_touch_down && !s_ptt_failed;
    const uint32_t ink = lit ? COLOR_INK : COLOR_AMBER;

    /* Ring around the mic. */
    draw_arc(layer, cx, cy, 44, 5, 0, 360, ink);

    /* Capsule. */
    lv_draw_rect_dsc_t rect;
    lv_draw_rect_dsc_init(&rect);
    rect.bg_opa = LV_OPA_TRANSP;
    rect.border_color = lv_color_hex(ink);
    rect.border_width = 4;
    rect.border_opa = LV_OPA_COVER;
    rect.radius = LV_RADIUS_CIRCLE;
    lv_area_t cap = { cx - 9, cy - 26, cx + 9, cy + 6 };
    lv_draw_rect(layer, &rect, &cap);

    /* Cradle (lower half arc), stem and base. */
    draw_arc(layer, cx, cy - 4, 17, 4, 0, 180, ink);
    draw_line(layer, (float)cx, (float)(cy + 13), (float)cx, (float)(cy + 22), 4, ink);
    draw_line(layer, (float)(cx - 10), (float)(cy + 23), (float)(cx + 10), (float)(cy + 23), 4, ink);
}

